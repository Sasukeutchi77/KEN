export function parsePh(d: string): string | null {
  for (let l = 3; l >= 1; l--) {
    const c = parseInt(d.substring(0, l), 10);
    if (!VC.has(c)) continue;
    const loc = d.substring(l);
    const r = CR[c];
    if (r) {
      if (loc.length >= r[0] && loc.length <= r[1]) return '+' + d;
    } else if (loc.length >= 4 && loc.length <= 12) {
      return '+' + d;
    }
  }
  return null;
}

export function getErr(d: string): string {
  if (!d) return 'Entrez le numéro avec indicatif';
  if (d.length < 3) return 'Continuez...';
  for (let l = 3; l >= 1; l--) {
    const c = parseInt(d.substring(0, l), 10);
    if (!VC.has(c)) continue;
    const loc = d.substring(l);
    const r = CR[c];
    if (!r) return loc.length < 4 ? 'Numéro incomplet' : '';
    if (loc.length < r[0]) return 'Numéro incomplet';
    if (loc.length > r[1]) return 'Numéro trop long';
    return '';
  }
  return 'Indicatif invalide';
}

export function fmtTs(date = new Date()): string {
  const hh = String(date.getHours()).padStart(2, '0');
  const mm = String(date.getMinutes()).padStart(2, '0');
  const dd = String(date.getDate()).padStart(2, '0');
  const mo = String(date.getMonth() + 1).padStart(2, '0');
  const yy = date.getFullYear();
  return `${hh}:${mm} | ${dd}/${mo}/${yy}`;
}

export function timeAgo(ts: number): string {
  const diff = Date.now() - ts;
  const m = Math.floor(diff / 60000);
  if (m < 1) return "À l'instant";
  if (m < 60) return `${m}m ago`;
  const h = Math.floor(m / 60);
  if (h < 24) return `${h}h ago`;
  const d = Math.floor(h / 24);
  return `${d}d ago`;
}
